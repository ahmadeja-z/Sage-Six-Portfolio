export function getPublishedInsights(): Insight[] {
  return insights
    .filter((i) => i.published)
    .sort((a, b) => (a.publishedAt < b.publishedAt ? 1 : -1));
}

export function getFeaturedInsight(): Insight | undefined {
  return getPublishedInsights().find((i) => i.featured);
}

export function getInsight(slug: string): Insight | undefined {
  return insights.find((i) => i.slug === slug);
}

export function getRelatedInsights(slug: string, count = 3): Insight[] {
  const article = getInsight(slug);
  if (!article) return [];
  const byId: Record<string, Insight> = {};
  for (const relatedSlug of article.relatedArticles) {
    const related = getInsight(relatedSlug);
    if (related && related.published) byId[relatedSlug] = related;
  }
  const linked = article.relatedArticles.map((s) => byId[s]).filter(Boolean);
  const rest = getPublishedInsights().filter((i) => i.slug !== slug && !byId[i.slug]);
  return [...linked, ...rest].slice(0, count);
}

